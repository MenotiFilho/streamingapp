#!/usr/bin/env bash
# Stage the Host where Windows can build and run it: a Windows path, as a copy,
# carrying the built frontend that `dist/` holds and git does not.
#
#   scripts/windows/stage.sh /mnt/c/Users/<you>/streamingapp-verify
#
# Run from WSL, in the repo root. `verify.ps1` runs the walkthrough afterwards.
#
# The Torrent engine is built here too, in the dev container (Go lives there, and
# Windows has none), and copied in with the licence notice that ships beside it.
# `scripts/cd.sh` builds it first, in its own pinned image, and says so with
# TORRENT_ENGINE_PREBUILT=1.
set -euo pipefail

target="${1:?usage: stage.sh <windows-path-as-seen-from-wsl>}"
repo="$(git rev-parse --show-toplevel)"
cd "$repo"

if [ ! -f dist/index.html ]; then
  echo "no frontend in ./dist — run 'docker compose exec dev pnpm build' first" >&2
  exit 1
fi

if [ -z "${TORRENT_ENGINE_PREBUILT:-}" ]; then
  docker compose up -d dev
  docker compose exec -T dev crates/host-torrent/build.sh
fi
engine=crates/host-torrent/out/streamingapp-torrent.exe
if [ ! -f "$engine" ]; then
  echo "no Torrent engine at $engine — run 'docker compose exec dev crates/host-torrent/build.sh'" >&2
  exit 1
fi

mkdir -p "$target"
# Committed files only: no target/, no node_modules/, no .git.
git archive HEAD | tar -x -C "$target"
rm -rf "$target/dist"
cp -r dist "$target/dist"
# The tree gets the scripts as they are now, not as they were last committed, so
# the walkthrough can be edited and re-run without a commit in between.
cp scripts/windows/*.ps1 "$target/scripts/windows/"
# The Torrent engine and its licences: build output git does not hold, and the
# notice as regenerated by the build that made the engine.
mkdir -p "$target/crates/host-torrent/out" "$target/crates/host-torrent/engine"
cp "$engine" "$target/crates/host-torrent/out/"
cp crates/host-torrent/engine/THIRD-PARTY.md "$target/crates/host-torrent/engine/"

# Walkthrough-only local torrent seeder (spec #311, issue #347): built only for
# a manual walkthrough tree — never by build.sh, cd.sh (which sets
# TORRENT_ENGINE_PREBUILT=1), or build.ps1, and never bundled into the installer.
if [ -z "${TORRENT_ENGINE_PREBUILT:-}" ]; then
  mkdir -p "$target/fixture"
  docker compose exec -T dev bash -c \
    "cd crates/host-torrent/engine && GOOS=windows GOARCH=amd64 CGO_ENABLED=0 go build -trimpath -o /tmp/fixture-seed.exe ./cmd/fixture-seed"
  docker compose cp dev:/tmp/fixture-seed.exe "$target/fixture/fixture-seed.exe" >/dev/null
  docker compose exec -T dev rm -f /tmp/fixture-seed.exe
fi

echo "staged $(git rev-parse --short HEAD) at $target"
if [ -f "$target/fixture/fixture-seed.exe" ]; then
  echo "fixture seeder: $(wc -c <"$target/fixture/fixture-seed.exe") bytes (walkthrough only, never bundled)"
fi
if [ -f "$target/fixture/verify-controls.mkv" ]; then
  echo "fixture video: $(wc -c <"$target/fixture/verify-controls.mkv") bytes (scripts/windows/fixture-video.sh)"
else
  echo "no fixture video yet — 'scripts/windows/fixture-video.sh $target' makes one,"
  echo "which is what lets a walkthrough play a Stream without a debrid Addon"
fi
echo "next: powershell -NoProfile -ExecutionPolicy Bypass -File 'C:\\...\\scripts\\windows\\build.ps1' -Tree '<windows path>'"
