#!/usr/bin/env bash
# Write engine/THIRD-PARTY.md: the licence of every Go module the Torrent engine
# is built from, with the text each one ships (ADR-0042 §1, ADR-0004).
#
#   docker compose exec dev crates/host-torrent/licenses.sh
#
# The list is read from the build itself — `go list -deps` for the Windows target
# the installer carries — so it is exactly what is linked in, not everything
# `go.mod` mentions, and it is sorted so that the file only changes when a
# dependency does. `build.sh` runs it; the output is committed and ships beside
# the engine in the installer, because MPL-2.0 §3.3's Larger Work needs the notices
# to travel with the binary.
#
# The identifier beside a module is a guess from the text's own wording, to be
# read as a heading; the text beneath it is the licence.
set -euo pipefail

here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
engine="$here/engine"
out="${1:-$engine/THIRD-PARTY.md}"

cd "$engine"
export GOOS=windows GOARCH=amd64 CGO_ENABLED=0

# `GOFLAGS=-mod=readonly` keeps a stale go.sum a failure, not a rewrite.
modules="$(GOFLAGS=-mod=readonly go list -deps \
  -f '{{if and .Module (not .Module.Main)}}{{.Module.Path}}|{{.Module.Version}}|{{.Module.Dir}}{{end}}' \
  ./... | sort -u)"

# A guess at the licence from its own wording; empty when it is not one we know.
identify() {
  local text
  text="$(tr -s '[:space:]' ' ' <"$1")"
  case "$text" in
    *"Mozilla Public License"*"ersion 2.0"* | *"Mozilla Public License"*", version 2.0"*) echo "MPL-2.0" ;;
    *"Apache License"*"Version 2.0"*) echo "Apache-2.0" ;;
    *"Redistribution and use in source and binary forms"*"Neither the name"*) echo "BSD-3-Clause" ;;
    *"Redistribution and use in source and binary forms"*) echo "BSD-2-Clause" ;;
    *"Permission is hereby granted, free of charge"*) echo "MIT" ;;
    *"with or without fee is hereby granted"*) echo "ISC" ;;
    *"This is free and unencumbered software released into the public domain"*) echo "Unlicense" ;;
    *) echo "see the text" ;;
  esac
}

# The licence files at the top of a module: LICENSE, LICENCE, COPYING, NOTICE and
# their variants. A directory of that name (REUSE's `LICENSES/`) is not one.
license_files() {
  find "$1" -maxdepth 1 -type f \
    \( -iname 'licen[sc]e*' -o -iname 'copying*' -o -iname 'notice*' -o -iname 'unlicense*' \) \
    | sort
}

{
  cat <<'HEADER'
# Third-party licences of the Torrent engine

<!-- Generated by crates/host-torrent/licenses.sh. Do not edit by hand. -->

The Torrent engine (`streamingapp-torrent`) is our own Go program, licensed
GPL-3.0-or-later like the rest of the Host. It is built from the Go standard
library and the modules below, each under its own licence, whose text follows.
`github.com/anacrolix/torrent` is MPL-2.0: the engine is a Larger Work in the sense
of its §3.3, distributed under the GPL, and the Source Code Form of that module is
available from its repository at the version listed.

HEADER

  echo "## Index"
  echo
  echo "| Module | Version | Licence |"
  echo "| --- | --- | --- |"
  goroot="$(go env GOROOT)"
  echo "| Go standard library | $(go env GOVERSION) | $(identify "$goroot/LICENSE") |"
  while IFS='|' read -r path version dir; do
    [ -n "$path" ] || continue
    files="$(license_files "$dir")"
    kind="no licence file shipped"
    if [ -n "$files" ]; then
      kinds=""
      while IFS= read -r file; do
        one="$(identify "$file")"
        case " $kinds " in *" $one "*) ;; *) kinds="${kinds:+$kinds, }$one" ;; esac
      done <<<"$files"
      kind="$kinds"
    fi
    echo "| \`$path\` | $version | $kind |"
  done <<<"$modules"
  echo

  echo "## Go standard library"
  echo
  echo '```text'
  cat "$goroot/LICENSE"
  echo '```'
  echo

  while IFS='|' read -r path version dir; do
    [ -n "$path" ] || continue
    echo "## $path $version"
    echo
    files="$(license_files "$dir")"
    if [ -z "$files" ]; then
      echo "_The module ships no licence file._"
      echo
      continue
    fi
    while IFS= read -r file; do
      echo "### $(basename "$file")"
      echo
      echo '```text'
      cat "$file"
      # A file that does not end in a newline must not run into the fence.
      [ -z "$(tail -c1 "$file")" ] || echo
      echo '```'
      echo
    done <<<"$files"
  done <<<"$modules"
} >"$out.tmp"

mv "$out.tmp" "$out"
echo "licences: $(grep -c '^## ' "$out") sections in $out"
